const USAGE: &str = "command-library - pick a command from the library with fzf and print it

Usage:
  command-library --config FILE [--query QUERY] [--expand]

Options:
  --config FILE      Command library JSON generated by Home Manager.
  -q, --query QUERY  Prefill the fzf query.
  --expand           Expand QUERY when it is exactly an alias; otherwise
                     pick from the entries whose tag matches its first word.
  -h, --help         Show this help.

Placeholders such as <name> are filled before the command is printed.";

const EXIT_CANCELLED: i32 = 130;

struct Args {
    config: String,
    query: String,
    expand: bool,
}

fn fail(message: &str) -> ! {
    eprintln!("command-library: {message}\n{USAGE}");
    exit(2);
}

fn parse_args(argv: Vec<String>) -> Args {
    let mut config = None;
    let mut query = String::new();
    let mut expand = false;
    let mut iter = argv.into_iter();
    while let Some(arg) = iter.next() {
        match arg.as_str() {
            "-h" | "--help" => {
                println!("{USAGE}");
                exit(0);
            }
            "--config" | "-q" | "--query" => {
                let Some(value) = iter.next() else {
                    fail(&format!("{arg} requires a value"));
                };
                if arg == "--config" {
                    config = Some(value);
                } else {
                    query = value;
                }
            }
            "--expand" => expand = true,
            _ => fail(&format!("unknown argument: {arg}")),
        }
    }
    let Some(config) = config else {
        fail("--config is required");
    };
    Args {
        config,
        query,
        expand,
    }
}

/// Runs fzf with `args`, feeding `input`; returns its exit code and stdout.
type Fzf<'a> = dyn FnMut(&[String], &str) -> Result<(i32, String), String> + 'a;

fn run_fzf(config: &Config, args: &[String], input: &str) -> Result<(i32, String), String> {
    let command = &config.fzf.command;
    let mut child = Command::new(command)
        .args(args)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::inherit())
        .spawn()
        .map_err(|error| format!("{command}: {error}"))?;
    let mut stdin = child.stdin.take().ok_or("fzf stdin is unavailable")?;
    let data = input.to_string();
    let writer = std::thread::spawn(move || {
        // fzf may exit before reading everything; a broken pipe is fine.
        let _ = stdin.write_all(data.as_bytes());
    });
    let output = child
        .wait_with_output()
        .map_err(|error| format!("{command}: {error}"))?;
    let _ = writer.join();
    Ok((
        output.status.code().unwrap_or(EXIT_CANCELLED),
        String::from_utf8_lossy(&output.stdout).into_owned(),
    ))
}

fn strings(values: &[&str]) -> Vec<String> {
    values.iter().map(|value| value.to_string()).collect()
}

fn select_item<'a>(
    config: &Config,
    list: &[Item<'a>],
    args: &Args,
    fzf: &mut Fzf,
) -> Result<Option<Item<'a>>, String> {
    let mut candidates = list.to_vec();
    let mut channel_name = None;
    let mut query = args.query.clone();
    if args.expand {
        if let Some(alias) = find_alias(list, &query) {
            return Ok(Some(alias));
        }
        let narrowed = channel(list, &query);
        channel_name = narrowed.name;
        candidates = narrowed.items;
        query = narrowed.query;
    }
    let mut fzf_args = config.fzf.options.clone();
    fzf_args.extend(FZF_LINE_OPTIONS.iter().map(|option| option.to_string()));
    fzf_args.push(
        if channel_name.is_some() && query.is_empty() {
            "--no-select-1"
        } else {
            "--select-1"
        }
        .to_string(),
    );
    fzf_args.extend(strings(&["--header"]));
    fzf_args.push(format_header(&candidates, channel_name.as_deref()));
    fzf_args.extend(strings(&["--query"]));
    fzf_args.push(query);
    let (code, stdout) = fzf(&fzf_args, &format_lines(&candidates).join("\n"))?;
    if code != 0 {
        return Ok(None);
    }
    let index = parse_selection(stdout.split('\n').next().unwrap_or(""));
    Ok(index
        .and_then(|index| usize::try_from(index).ok())
        .and_then(|index| candidates.get(index).copied()))
}

struct FzfPrompter<'a> {
    config: &'a Config,
}

impl FzfPrompter<'_> {
    fn base(&self, name: &str, header: &str) -> Vec<String> {
        let mut args = self.config.fzf.variable_options.clone();
        args.extend([
            "--prompt".to_string(),
            format!("{name}: "),
            "--header".to_string(),
            format!("command: {header}"),
        ]);
        args
    }
}

impl Prompter for FzfPrompter<'_> {
    fn run(&mut self, command: &str) -> String {
        Command::new("sh")
            .args(["-c", command])
            .stdin(Stdio::inherit())
            .stdout(Stdio::piped())
            .stderr(Stdio::inherit())
            .output()
            .map(|output| String::from_utf8_lossy(&output.stdout).into_owned())
            .unwrap_or_default()
    }

    fn choose(
        &mut self,
        name: &str,
        variable: &Variable,
        candidates: &Candidates,
        header: &str,
    ) -> Result<Option<Vec<String>>, String> {
        let mut args = self.base(name, header);
        if !candidates.headers.is_empty() {
            args.push("--header-lines".to_string());
            args.push(candidates.headers.len().to_string());
        }
        if variable.multi {
            args.push("--multi".to_string());
        }
        let input = candidates
            .headers
            .iter()
            .chain(&candidates.values)
            .cloned()
            .collect::<Vec<_>>()
            .join("\n");
        let (code, stdout) = run_fzf(self.config, &args, &input)?;
        if code != 0 {
            return Ok(None);
        }
        Ok(Some(
            stdout
                .split('\n')
                .filter(|line| !line.is_empty())
                .map(str::to_string)
                .collect(),
        ))
    }

    fn input(&mut self, name: &str, header: &str) -> Result<Option<String>, String> {
        // With no candidates fzf exits 1 on enter but still prints the query.
        let mut args = self.base(name, header);
        args.push("--print-query".to_string());
        let (code, stdout) = run_fzf(self.config, &args, "")?;
        if code != 0 && code != 1 {
            return Ok(None);
        }
        Ok(Some(stdout.split('\n').next().unwrap_or("").to_string()))
    }
}

struct SystemEnvironment {
    cwd: String,
    home: String,
    path_dirs: Vec<std::path::PathBuf>,
}

impl SystemEnvironment {
    fn new() -> Self {
        let path = std::env::var_os("PATH").unwrap_or_default();
        Self {
            cwd: std::env::current_dir()
                .map(|dir| dir.to_string_lossy().into_owned())
                .unwrap_or_default(),
            home: std::env::var("HOME").unwrap_or_default(),
            path_dirs: std::env::split_paths(&path)
                .filter(|dir| !dir.as_os_str().is_empty())
                .collect(),
        }
    }
}

impl Environment for SystemEnvironment {
    fn cwd(&self) -> &str {
        &self.cwd
    }

    fn home(&self) -> &str {
        &self.home
    }

    fn exists(&self, path: &str) -> bool {
        std::path::Path::new(path).exists()
    }

    fn has_command(&self, name: &str) -> bool {
        self.path_dirs.iter().any(|dir| {
            std::fs::metadata(dir.join(name))
                .is_ok_and(|metadata| metadata.permissions().mode() & 0o111 != 0)
        })
    }
}

fn run() -> Result<i32, String> {
    let args = parse_args(
        std::env::args_os()
            .skip(1)
            .map(|arg| arg.to_string_lossy().into_owned())
            .collect(),
    );
    let config = load_config(&args.config)?;
    let environment = SystemEnvironment::new();
    let list = items(&config, Some(&environment));
    let item = select_item(&config, &list, &args, &mut |fzf_args, input| {
        run_fzf(&config, fzf_args, input)
    })?;
    let Some(item) = item else {
        return Ok(EXIT_CANCELLED);
    };
    let Some(command) = resolve_command(&item, &mut FzfPrompter { config: &config })? else {
        return Ok(EXIT_CANCELLED);
    };
    println!("{command}");
    Ok(0)
}

fn main() {
    match run() {
        Ok(code) => exit(code),
        Err(message) => {
            eprintln!("command-library: {message}");
            exit(1);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use library::{Entry, FzfConfig, Section};

    fn config() -> Config {
        Config {
            fzf: FzfConfig {
                command: "fzf".to_string(),
                ..FzfConfig::default()
            },
            sections: vec![Section {
                tags: vec!["nix apply".to_string()],
                entries: vec![Entry {
                    description: "apply configuration".to_string(),
                    alias: Some("switch".to_string()),
                    command: "nix run .#apply".to_string(),
                }],
                ..Section::default()
            }],
        }
    }

    /// Completes `query` with a fake fzf that picks the first line.
    fn complete(config: &Config, query: &str) -> (Option<String>, Vec<Vec<String>>) {
        let args = Args {
            config: "test.json".to_string(),
            query: query.to_string(),
            expand: true,
        };
        let list = items(config, None);
        let mut calls = Vec::new();
        let item = select_item(config, &list, &args, &mut |fzf_args, input| {
            calls.push(fzf_args.to_vec());
            Ok((0, format!("{}\n", input.split('\n').next().unwrap_or(""))))
        })
        .unwrap();
        (item.map(|item| item.entry.command.clone()), calls)
    }

    fn tail(args: &[String]) -> &[String] {
        &args[args.len() - 2..]
    }

    #[test]
    fn auto_selects_a_command_matching_a_query_without_a_channel() {
        let (command, calls) = complete(&config(), "apply");
        assert_eq!(calls.len(), 1);
        let args = &calls[0];
        assert!(args.contains(&"--select-1".to_string()));
        assert_eq!(tail(args), ["--query", "apply"]);
        let nth = args.iter().position(|arg| arg == "--nth").unwrap();
        assert_eq!(args[nth..nth + 2], ["--nth", "2"]);
        assert_eq!(command.as_deref(), Some("nix run .#apply"));
    }

    #[test]
    fn searches_for_a_command_after_removing_its_channel_from_the_query() {
        let (command, calls) = complete(&config(), "nix apply");
        assert_eq!(calls.len(), 1);
        assert!(calls[0].contains(&"--select-1".to_string()));
        assert_eq!(tail(&calls[0]), ["--query", "apply"]);
        assert_eq!(command.as_deref(), Some("nix run .#apply"));
    }

    #[test]
    fn keeps_the_picker_open_for_a_channel_containing_only_one_entry() {
        let mut config = config();
        config.fzf.options = vec!["--select-1".to_string()];
        let (_, calls) = complete(&config, "nix");
        assert_eq!(calls.len(), 1);
        let args = &calls[0];
        let last = |name: &str| args.iter().rposition(|arg| arg == name).unwrap();
        assert!(last("--no-select-1") > last("--select-1"));
        assert_eq!(tail(args), ["--query", ""]);
    }

    #[test]
    fn expands_exact_aliases_without_opening_the_picker() {
        let (command, calls) = complete(&config(), "switch");
        assert!(calls.is_empty());
        assert_eq!(command.as_deref(), Some("nix run .#apply"));
    }
}
