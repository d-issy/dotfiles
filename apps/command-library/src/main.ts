import { spawnSync } from "node:child_process";
import { accessSync, constants, existsSync } from "node:fs";
import { homedir } from "node:os";
import { delimiter, join } from "node:path";
import {
	type Config,
	type Environment,
	FZF_LINE_OPTIONS,
	type Item,
	channel,
	findAlias,
	formatHeader,
	formatLines,
	items,
	loadConfig,
	parseSelection,
} from "./library";
import { type Prompter, resolveCommand } from "./resolve";

const USAGE = `dot-command-library - pick a command from the library with fzf and print it

Usage:
  dot-command-library --config FILE [--query QUERY] [--expand]

Options:
  --config FILE      Command library JSON generated by Home Manager.
  -q, --query QUERY  Prefill the fzf query.
  --expand           Expand QUERY when it is exactly an alias; otherwise
                     pick from the entries whose tag matches its first word.
  -h, --help         Show this help.

Placeholders such as <name> are filled before the command is printed.`;

const MAX_BUFFER = 64 * 1024 * 1024;
const EXIT_CANCELLED = 130;

interface Args {
	config: string;
	query: string;
	expand: boolean;
}

function fail(message: string): never {
	process.stderr.write(`dot-command-library: ${message}\n${USAGE}\n`);
	process.exit(2);
}

function parseArgs(argv: string[]): Args {
	let config: string | undefined;
	let query = "";
	let expand = false;
	for (let index = 0; index < argv.length; index++) {
		const arg = argv[index];
		const value = (): string => {
			const next = argv[++index];
			if (next === undefined) fail(`${arg} requires a value`);
			return next;
		};
		if (arg === "-h" || arg === "--help") {
			process.stdout.write(`${USAGE}\n`);
			process.exit(0);
		} else if (arg === "--config") config = value();
		else if (arg === "-q" || arg === "--query") query = value();
		else if (arg === "--expand") expand = true;
		else fail(`unknown argument: ${arg}`);
	}
	if (config === undefined) fail("--config is required");
	return { config, query, expand };
}

function fzf(
	config: Config,
	args: string[],
	input: string,
): { code: number; stdout: string } {
	const result = spawnSync(config.fzf.command, args, {
		input,
		encoding: "utf8",
		maxBuffer: MAX_BUFFER,
		stdio: ["pipe", "pipe", "inherit"],
	});
	if (result.error) throw result.error;
	return { code: result.status ?? EXIT_CANCELLED, stdout: result.stdout };
}

function selectItem(config: Config, list: Item[], args: Args): Item | null {
	let candidates = list;
	let channelName: string | null = null;
	let query = args.query;
	if (args.expand) {
		const alias = findAlias(list, args.query);
		if (alias !== undefined) return alias;
		({ name: channelName, items: candidates, query } = channel(list, query));
	}
	const { code, stdout } = fzf(
		config,
		[
			...config.fzf.options,
			...FZF_LINE_OPTIONS,
			channelName !== null && query === "" ? "--no-select-1" : "--select-1",
			"--header",
			formatHeader(candidates, channelName),
			"--query",
			query,
		],
		formatLines(candidates).join("\n"),
	);
	if (code !== 0) return null;
	const index = parseSelection(stdout.split("\n")[0] ?? "");
	return index === undefined ? null : (candidates[index] ?? null);
}

function prompter(config: Config): Prompter {
	const base = (name: string, header: string): string[] => [
		...config.fzf.variableOptions,
		"--prompt",
		`${name}: `,
		"--header",
		`command: ${header}`,
	];
	return {
		run(command) {
			const result = spawnSync("sh", ["-c", command], {
				encoding: "utf8",
				maxBuffer: MAX_BUFFER,
				stdio: ["inherit", "pipe", "inherit"],
			});
			return result.stdout ?? "";
		},
		choose(name, variable, candidates, header) {
			const args = base(name, header);
			if (candidates.headers.length > 0)
				args.push("--header-lines", String(candidates.headers.length));
			if (variable.multi) args.push("--multi");
			const { code, stdout } = fzf(
				config,
				args,
				[...candidates.headers, ...candidates.values].join("\n"),
			);
			if (code !== 0) return null;
			return stdout.split("\n").filter((line) => line !== "");
		},
		input(name, header) {
			// With no candidates fzf exits 1 on enter but still prints the query.
			const { code, stdout } = fzf(
				config,
				[...base(name, header), "--print-query"],
				"",
			);
			if (code !== 0 && code !== 1) return null;
			return stdout.split("\n")[0] ?? "";
		},
	};
}

function isExecutable(path: string): boolean {
	try {
		accessSync(path, constants.X_OK);
		return true;
	} catch {
		return false;
	}
}

function environment(): Environment {
	const dirs = (process.env.PATH ?? "").split(delimiter).filter(Boolean);
	return {
		cwd: process.cwd(),
		home: homedir(),
		exists: existsSync,
		hasCommand: (name) => dirs.some((dir) => isExecutable(join(dir, name))),
	};
}

function main(): void {
	const args = parseArgs(process.argv.slice(2));
	const config = loadConfig(args.config);
	const item = selectItem(config, items(config, environment()), args);
	if (item === null) process.exit(EXIT_CANCELLED);
	const command = resolveCommand(item, prompter(config));
	if (command === null) process.exit(EXIT_CANCELLED);
	process.stdout.write(`${command}\n`);
}

main();
